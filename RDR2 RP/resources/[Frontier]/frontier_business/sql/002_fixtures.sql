CREATE TABLE IF NOT EXISTS fb_fixtures (
 id CHAR(32) PRIMARY KEY,property_id CHAR(32) NOT NULL,owner_type VARCHAR(12) NOT NULL,owner_id VARCHAR(64) NOT NULL,kind VARCHAR(12) NOT NULL,name VARCHAR(60) NOT NULL,grantor VARCHAR(64) NOT NULL,INDEX(owner_type,owner_id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS fb_prices (
 fixture_id CHAR(32) NOT NULL,item_id VARCHAR(48) NOT NULL,price BIGINT UNSIGNED NOT NULL,PRIMARY KEY(fixture_id,item_id),FOREIGN KEY(fixture_id) REFERENCES fb_fixtures(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS fb_retail (
 id CHAR(32) PRIMARY KEY,fixture_id CHAR(32) NOT NULL,buyer VARCHAR(64) NOT NULL,buyer_bank BIGINT UNSIGNED NOT NULL,seller_type VARCHAR(12) NOT NULL,seller_id VARCHAR(64) NOT NULL,seller_bank BIGINT UNSIGNED NOT NULL,item_id VARCHAR(48) NOT NULL,quantity INT NOT NULL,price BIGINT UNSIGNED NOT NULL,state VARCHAR(16) NOT NULL,created BIGINT NOT NULL,INDEX(buyer,state)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS fb_storage_audit (
 request_id VARCHAR(96) NOT NULL,fixture_id CHAR(32) NOT NULL,actor VARCHAR(64) NOT NULL,action VARCHAR(24) NOT NULL,detail LONGTEXT NOT NULL,created BIGINT NOT NULL,PRIMARY KEY(request_id,actor)
) ENGINE=InnoDB;
