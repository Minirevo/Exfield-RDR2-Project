CREATE TABLE IF NOT EXISTS frontier_gather_nodes(
 id VARCHAR(90) CHARACTER SET ascii COLLATE ascii_bin PRIMARY KEY,
 action VARCHAR(24) NOT NULL, model BIGINT NOT NULL DEFAULT 0,
 x DOUBLE NOT NULL,y DOUBLE NOT NULL,z DOUBLE NOT NULL,
 remaining INT NOT NULL,next_at BIGINT NOT NULL DEFAULT 0,
 INDEX ix_gather_respawn(next_at)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS frontier_gather_survey(
 id VARCHAR(90) CHARACTER SET ascii COLLATE ascii_bin PRIMARY KEY,
 action VARCHAR(24) NOT NULL,model BIGINT NOT NULL DEFAULT 0,
 x DOUBLE NOT NULL,y DOUBLE NOT NULL,z DOUBLE NOT NULL
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS frontier_gather_claims(
 id CHAR(32) CHARACTER SET ascii COLLATE ascii_bin PRIMARY KEY,
 character_id VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 skill VARCHAR(24) NOT NULL,payload TEXT NOT NULL,phase TINYINT NOT NULL DEFAULT 0,
 created BIGINT NOT NULL,INDEX ix_gather_pending(character_id,phase)
) ENGINE=InnoDB;
