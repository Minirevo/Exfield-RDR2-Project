dofile('config.lua');dofile('model.lua')
local M,C=FrontierMedicalModel,FrontierMedicalConfig
local s=M.new();assert(M.status(s,0)=='stable' and M.bleed(s)==0)
assert(M.injure(s,'left_leg','fall',30,0))
assert(s.wounds.left_leg.fracture and M.restrictions(s).legs)
assert(M.treat(s,'splint','left_leg',0) and not M.restrictions(s).legs)
assert(not M.treat(s,'splint','left_leg',0))
assert(M.injure(s,'chest','penetrating',50,0))
local blood=s.blood;M.tick(s,5,true);assert(s.blood<blood)
assert(M.choose(s,'bandage',5)=='chest')
assert(M.treat(s,'bandage','chest',5))
assert(M.treat(s,'bandage','left_leg',5))
assert(M.bleed(s)==0)
blood=s.blood;M.tick(s,10,false);assert(s.blood==blood)
M.tick(s,15,true);assert(s.blood>blood)
local pain=s.pain;assert(M.treat(s,'tonic','head',15))
assert(M.pain(s,16)<pain and not M.treat(s,'tonic','head',16))
s.blood=300;M.updateDown(s,20);assert(s.down)
s.blood=500;s.pain=0;M.updateDown(s,21);assert(not s.down)
s.blood=0;M.updateDown(s,22);assert(M.status(s,22)=='dead' and not M.treat(s,'bandage','chest',22))
assert(M.new(s.life+1).life==2)
print('Medical model checks passed')
