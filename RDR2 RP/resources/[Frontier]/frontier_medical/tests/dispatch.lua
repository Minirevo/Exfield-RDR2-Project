dofile('dispatch.lua')
local D=FrontierMedicalDispatch
local b=D.new()
local p={x=1,y=2,z=3}
local c,new=D.open(b,1,'patient',1,0,p)
assert(new and c.number==1)
local same,again=D.open(b,1,'patient',1,0,p);assert(same==c and not again)
b.duty[2]='medic';b.duty[3]='other'
assert(not D.claim(b,c,1,'patient',0))
assert(not D.claim(b,c,2,'medic',1))
assert(not D.claim(b,c,4,'unknown',0))
assert(D.claim(b,c,2,'medic',0))
assert(D.claim(b,c,2,'medic',0))
assert(not D.claim(b,c,3,'other',0))
local second=D.open(b,4,'patient2',1,0,p)
assert(not D.claim(b,second,2,'medic',0))
assert(D.release(c)==2 and not c.responder)
assert(D.claim(b,c,3,'other',0))
assert(D.find(b,1)==c and D.close(b,c) and not D.find(b,1))
assert(not D.claim(b,c,2,'medic',0))
assert(D.same(second,'patient2',1,0))
assert(not D.same(second,'patient2',2,0))
assert(not D.same(second,'patient2',1,1))
print('Dispatch deduplication, assignment, duty, bucket, life and closure checks passed')
