dofile('hospital_config.lua');dofile('hospital_rules.lua')
local C,R=FrontierHospitalConfig,FrontierHospitalRules
local list,total=R.plan('kit','standard',1,{})
assert(#list==5 and total==750)
local again,zero=R.plan('kit','standard',1,{bandage=5,splint=2,tonic=2,stethoscope=1,thermometer=1})
assert(#again==0 and zero==0)
local partial,price=R.plan('kit','standard',1,{bandage=4,splint=2,tonic=2,stethoscope=1,thermometer=1})
assert(#partial==1 and partial[1].item=='bandage' and partial[1].count==1 and price==25)
local capped,value=R.plan('item','bandage',4,{bandage=9})
assert(#capped==1 and capped[1].count==1 and value==25)
assert(not R.plan('item','bandage',-1,{}))
assert(not R.plan('item','bandage',1.5,{}))
assert(not R.plan('kit','unknown',1,{}))
assert(R.status({status='pending',due_at=20},19)=='pending')
assert(R.status({status='pending',due_at=20},20)=='overdue')
assert(R.status({status='paid',due_at=20},21)=='paid')
assert(R.payable('pending') and R.payable('reported') and not R.payable('paying') and not R.payable('paid'))
print('Hospital kit top-up, price, quantity cap and invoice status checks passed')
